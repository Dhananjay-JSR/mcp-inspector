import esbuild from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const ui = resolve(root, "packages/ui");
const out = resolve(root, "dist/ui");
const production = process.argv.includes("--production");

await mkdir(out, { recursive: true });

await esbuild.build({
  entryPoints: [resolve(ui, "app.js")],
  outfile: resolve(out, "app.js"),
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2022",
  sourcemap: !production,
  minify: production,
  logLevel: "info",
});

await esbuild.build({
  entryPoints: [resolve(ui, "styles.css")],
  outfile: resolve(out, "styles.css"),
  bundle: true,
  minify: production,
  logLevel: "info",
});

/**
 * The host needs the skeleton as a string on both the desktop and the web
 * extension host, where there is no filesystem. Inline it into a generated
 * module instead of reading index.html at runtime.
 */
const html = await readFile(resolve(ui, "index.html"), "utf8");
const generated = `// Generated by scripts/build-ui.mjs. Edit packages/ui/index.html instead.
export const uiTemplate = ${JSON.stringify(html)};
`;
await writeFile(resolve(root, "src/views/uiTemplate.generated.ts"), generated);
console.log("ui: built dist/ui and src/views/uiTemplate.generated.ts");
